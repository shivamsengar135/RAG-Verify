"""Ablation table (single 300-question test block seed0 per dataset; see configs/grids.yaml "ablations").

Only one block per variant, so no std over seeds: each Phi_1 difference gets a paired bootstrap 95% CI
(10k resamples, seed 0) against its reference on the same 300 questions (RAG-Verify, or RAG for rag_k*).

Usage: .venv\\Scripts\\python.exe code\\aggregate_ablations.py
Output: results/tables/ablations.csv, paper/tables/ablation_rows.tex
"""
import csv

import numpy as np

from aggregate import DATASETS, load, phi_scores
from common import ROOT

SPLIT = "seed0"
ROWS = [  # (method id, display name, reference); None marks a group rule in the LaTeX table
    ("ragverify", "RAG-Verify (full, $k$=5, $\\tau$=0.3)", None),
    ("rv_no_retrieval", "$-$ retrieval (sample consistency)", "ragverify"),
    ("rv_no_decomp", "$-$ claim decomposition", "ragverify"),
    ("rv_no_verifier", "$-$ verifier (self-revision)", "ragverify"),
    ("rv_no_revision", "$-$ revision", "ragverify"),
    ("rv_no_abstain", "$-$ abstention gate", "ragverify"),
    None,
    ("rv_nli_only", "Verifier: NLI only", "ragverify"),
    ("rv_llm_judge", "Verifier: LLM judge only", "ragverify"),
    None,
    ("rv_tau05", "$\\tau$=0.5", "ragverify"),
    ("rv_tau07", "$\\tau$=0.7", "ragverify"),
    ("rv_tau09", "$\\tau$=0.9", "ragverify"),
    None,
    ("rv_k1", "$k$=1", "ragverify"),
    ("rv_k3", "$k$=3", "ragverify"),
    ("rv_k10", "$k$=10", "ragverify"),
    None,
    ("rag", "Standard RAG ($k$=5)", None),
    ("rag_k1", "Standard RAG, $k$=1", "rag"),
    ("rag_k3", "Standard RAG, $k$=3", "rag"),
    ("rag_k10", "Standard RAG, $k$=10", "rag"),
]


def num(x):
    return f"{x:+.1f}".replace("-", "$-$") if x < 0 else f"{x:+.1f}"


def main():
    rng = np.random.default_rng(0)
    out, lines = [], []
    for row in ROWS:
        if row is None:
            lines.append("\\midrule")
            continue
        m, name, ref = row
        cells = [name]
        for ds in DATASETS:
            d = load(ds, m, SPLIT)
            if d is None:
                out.append({"dataset": ds, "method": m, "status": "pending"})
                cells += ["\\pending{}"] * 2
                continue
            s = d["summary"]
            rec = {"dataset": ds, "method": m, "status": "done", "n": s["n"], "accuracy": s["accuracy"],
                   "abstention_rate": s["abstention_rate"], "hallucination_rate": s["hallucination_rate"],
                   "phi1": s["accuracy"] - s["hallucination_rate"], "llm_calls": s["llm_calls"], "ref": ref or ""}
            dcell = "--"
            r = load(ds, ref, SPLIT) if ref else None
            if r is not None:
                sa, sb = phi_scores(d), phi_scores(r)
                diff = np.array([sa[i] - sb[i] for i in sorted(sa)], dtype=float)
                boots = diff[rng.integers(0, len(diff), size=(10000, len(diff)))].mean(1)
                lo, hi = np.percentile(boots, [2.5, 97.5])
                rec.update(delta_phi1=diff.mean(), ci_lo=lo, ci_hi=hi)
                dcell = f"{num(100 * diff.mean())} [{num(100 * lo)}, {num(100 * hi)}]" + ("$^{*}$" if lo > 0 or hi < 0 else "")
            elif ref:
                dcell = "\\pending{}"
            out.append(rec)
            cells += [f"{100 * rec['phi1']:.1f}".replace("-", "$-$"), dcell]  # abst/hall stay in the CSV
        lines.append(" & ".join(cells) + " \\\\")
    (ROOT / "results" / "tables").mkdir(parents=True, exist_ok=True)
    keys = ["dataset", "method", "status", "ref", "n", "accuracy", "abstention_rate", "hallucination_rate", "phi1",
            "llm_calls", "delta_phi1", "ci_lo", "ci_hi"]
    with (ROOT / "results" / "tables" / "ablations.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=keys)
        w.writeheader()
        w.writerows(out)
    (ROOT / "paper" / "tables" / "ablation_rows.tex").write_text(
        "% AUTO-GENERATED by code/aggregate_ablations.py -- do not edit by hand\n" + "\n".join(lines) + "\n",
        encoding="utf-8")
    done = [r for r in out if r["status"] == "done"]
    print(f"{len(done)} of {len(out)} (variant, dataset) cells done")
    for r in done:
        extra = f" dPhi1={r['delta_phi1']:+.3f} [{r['ci_lo']:+.3f}, {r['ci_hi']:+.3f}]" if "delta_phi1" in r else ""
        print(f"{r['dataset']:9s} {r['method']:16s} abst={r['abstention_rate']:.3f} hall={r['hallucination_rate']:.3f} "
              f"phi1={r['phi1']:+.3f}{extra}")


if __name__ == "__main__":
    main()
