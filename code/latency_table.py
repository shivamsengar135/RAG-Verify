"""Controlled latency benchmark summary (first 50 dev questions per dataset, one system at a time, AC power).

Reads results/metrics/<ds>/<method>/dev_latency.json (made by code/run_extras.py) and, for the test-set
claim precision, results/metrics/<ds>/<method>/seed0.json.
Usage: .venv\\Scripts\\python.exe code\\latency_table.py
Output: results/tables/latency_claims.csv, paper/tables/cost_rows.tex
"""
import csv
import json

import numpy as np

from common import ROOT

DATASETS = ["hotpotqa", "triviaqa"]
SYSTEMS = [("closed_book", "Closed-book"), ("rag", "Standard RAG"), ("rag_abstain", "RAG + abstain prompt"),
           ("rv_no_verifier", "RAG + self-revision"), ("cove_rag", "CoVe + RAG"), ("ragverify", "RAG-Verify")]


def read(ds, m, name):
    p = ROOT / "results" / "metrics" / ds / m / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def main():
    rows, lines = [], []
    for m, label in SYSTEMS:
        cells = [label]
        for ds in DATASETS:
            lat, s0 = read(ds, m, "dev_latency"), read(ds, m, "seed0")
            r = {"dataset": ds, "method": m}
            if lat:
                L = [x["latency_s"] for x in lat["per_example"]]
                r.update(n_latency=len(L), latency_median=float(np.median(L)), latency_mean=float(np.mean(L)),
                         llm_calls=lat["summary"]["llm_calls"])
            if s0 and s0["summary"].get("claim_precision") is not None:
                r.update(claim_precision=s0["summary"]["claim_precision"], claims_per_answer=s0["summary"]["claims_per_answer"])
            rows.append(r)
            cells.append(f"{r['latency_median']:.1f}" if "latency_median" in r else "--")
            cells.append(f"{100 * r['claim_precision']:.1f}" if "claim_precision" in r else "\\pending{}")
        lines.append(" & ".join(cells) + " \\\\")
    keys = ["dataset", "method", "n_latency", "latency_median", "latency_mean", "llm_calls", "claim_precision", "claims_per_answer"]
    with (ROOT / "results" / "tables" / "latency_claims.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=keys)
        w.writeheader()
        w.writerows(rows)
    (ROOT / "paper" / "tables" / "cost_rows.tex").write_text(
        "% AUTO-GENERATED by code/latency_table.py -- do not edit by hand\n" + "\n".join(lines) + "\n", encoding="utf-8")
    for r in rows:
        print(r)


if __name__ == "__main__":
    main()
